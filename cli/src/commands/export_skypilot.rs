//! `gryvia export skypilot`: print a SkyPilot task YAML that targets a Kubernetes cluster
//! (run SkyPilot *on* Gryvia; Gryvia is not a multi-cloud broker).

use anyhow::{bail, Context, Result};
use kube::api::ListParams;
use serde_json::Value;

use crate::client::GryviaClient;
use crate::display;

/// Export one GryviaAIJob (by name) or stdin-less default: the newest job in the namespace.
pub async fn skypilot(client: &GryviaClient, name: Option<&str>) -> Result<()> {
    let api = super::capacity::gvk_api(client, "GryviaAIJob", "gryviaaijobs");
    let job = if let Some(n) = name {
        let obj = api
            .get(n)
            .await
            .map_err(|e| {
                anyhow::anyhow!(
                    "Failed to get job {n}: {}",
                    display::cluster_error_text(&e.to_string())
                )
            })?;
        serde_json::to_value(obj)?
    } else {
        let list = api
            .list(&ListParams::default())
            .await
            .map_err(|e| {
                anyhow::anyhow!(
                    "Failed to list jobs: {}",
                    display::cluster_error_text(&e.to_string())
                )
            })?;
        let mut items: Vec<Value> = list
            .items
            .iter()
            .filter_map(|o| serde_json::to_value(o).ok())
            .collect();
        if items.is_empty() {
            bail!("no GryviaAIJob in namespace {}; pass a job name", client.namespace());
        }
        items.sort_by(|a, b| {
            let ta = a
                .pointer("/metadata/creationTimestamp")
                .and_then(Value::as_str)
                .unwrap_or("");
            let tb = b
                .pointer("/metadata/creationTimestamp")
                .and_then(Value::as_str)
                .unwrap_or("");
            tb.cmp(ta)
        });
        items.remove(0)
    };

    let yaml = render_skypilot(&job).context("render SkyPilot YAML")?;
    println!("{yaml}");
    Ok(())
}

/// Build a minimal SkyPilot task from a GryviaAIJob JSON object.
pub fn render_skypilot(job: &Value) -> Result<String> {
    let name = job
        .pointer("/metadata/name")
        .and_then(Value::as_str)
        .unwrap_or("gryvia-job");
    let image = job
        .pointer("/spec/image")
        .and_then(Value::as_str)
        .unwrap_or("pytorch/pytorch:latest");
    let gpus = job
        .pointer("/spec/gpus")
        .and_then(Value::as_i64)
        .unwrap_or(0);
    let gpu_type = job
        .pointer("/spec/gpuType")
        .and_then(Value::as_str)
        .unwrap_or("");
    let cmd = job
        .pointer("/spec/command")
        .and_then(Value::as_array)
        .map(|a| {
            a.iter()
                .filter_map(Value::as_str)
                .collect::<Vec<_>>()
                .join(" ")
        })
        .filter(|s| !s.is_empty())
        .unwrap_or_else(|| "echo 'set run: in SkyPilot YAML'".into());

    let mut accelerators = String::new();
    if gpus > 0 {
        if gpu_type.is_empty() {
            accelerators = format!("  accelerators: A100:{gpus}\n");
        } else {
            accelerators = format!("  accelerators: {gpu_type}:{gpus}\n");
        }
    }

    Ok(format!(
        r#"# Generated by gryvia export skypilot from GryviaAIJob/{name}
# Run on a Kubernetes cluster that already has Gryvia (SkyPilot k8s backend).
# Gryvia does not broker multi-cloud capacity — see docs/skypilot.md.
name: {name}

resources:
  cloud: kubernetes
{accelerators}  image_id: docker:{image}
  # Optional: autostop idle workers (SkyPilot-native; Gryvia job idleTimeout is separate)
  # autostop: 10

setup: |
  echo "SkyPilot setup on Gryvia cluster"

run: |
  {cmd}
"#
    ))
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn renders_basic() {
        let job = json!({
            "metadata": {"name": "train"},
            "spec": {
                "image": "pytorch/pytorch:2.4.0",
                "gpus": 2,
                "gpuType": "H100",
                "command": ["python", "train.py"]
            }
        });
        let y = render_skypilot(&job).unwrap();
        assert!(y.contains("name: train"));
        assert!(y.contains("accelerators: H100:2"));
        assert!(y.contains("python train.py"));
        assert!(y.contains("cloud: kubernetes"));
    }
}
