"""Generate web/tokens.css and native Brand.swift from brand/tokens.json (single source of truth)."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
t = json.loads((root / "brand/tokens.json").read_text())


def css() -> str:
    out = ["/* GENERATED by scripts/gen-brand.py from brand/tokens.json. Do not edit. */", ":root {"]
    out.append(f"  --accent-color: {t['accent']};")
    out.append("  --accent-soft: color-mix(in srgb, var(--accent-color) 14%, transparent);")
    out.append("  --accent-text: color-mix(in srgb, var(--accent-color) 82%, black);")
    out.append("  --on-accent: #fff;")
    for k, v in t["status"].items():
        out.append(f"  --status-{k}: {v};")
    for k, v in t["light"].items():
        out.append(f"  --{k}: {v};")
    out.append("}")
    for name, hexv in t["accents"].items():
        out.append(f':root[data-accent="{name}"] {{ --accent-color: {hexv}; }}')
    out.append("@media (prefers-color-scheme: dark) {\n  :root:not([data-theme=\"light\"]) {")
    for k, v in t["dark"].items():
        out.append(f"    --{k}: {v};")
    out.append("  }\n}")
    out.append(":root[data-theme=\"dark\"] {")
    for k, v in t["dark"].items():
        out.append(f"  --{k}: {v};")
    out.append("}")
    return "\n".join(out) + "\n"


def swift() -> str:
    def hexrgb(h: str) -> str:
        h = h.lstrip("#")
        return f"0x{h.upper()}"
    lines = [
        "// GENERATED by scripts/gen-brand.py from brand/tokens.json. Do not edit.",
        "// SPDX-License-Identifier: BUSL-1.1",
        "// Copyright © 2026 Zyvor AI Labs Private Limited",
        "public enum Brand {",
        f"    public static let accentHex: UInt32 = {hexrgb(t['accent'])}",
        "    public static let accents: [(name: String, hex: UInt32)] = [",
    ]
    for k, v in t["accents"].items():
        lines.append(f'        ("{k}", {hexrgb(v)}),')
    lines += ["    ]", "    public static let status: [String: UInt32] = ["]
    for k, v in t["status"].items():
        lines.append(f'        "{k}": {hexrgb(v)},')
    lines += ["    ]", "}", ""]
    return "\n".join(lines)


(root / "web/tokens.css").write_text(css())
(root / "native/Sources/GryviaCore/Brand.swift").write_text(swift())
print("generated web/tokens.css and Brand.swift")
